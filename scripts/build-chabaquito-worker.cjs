'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const shared=fs.readFileSync(path.join(root,'functions/loyalty-season-policy.js'),'utf8');
const source=fs.readFileSync(path.join(root,'workers/chabaquito/src/index.js'),'utf8');
const expected="import '../../../functions/loyalty-season-policy.js';";
if(!source.startsWith(expected))throw Error('Revisa la importación del Worker antes de generar el archivo único.');
const consumption=fs.readFileSync(path.join(root,'functions/loyalty-consumption.js'),'utf8');
const output='/* Generated by scripts/build-chabaquito-worker.cjs. Review in an isolated preview; do not replace production without approval. */\n'+shared+'\n'+consumption+'\n'+source.slice(expected.length).replace("import '../../../functions/loyalty-consumption.js';",'').trimStart();
fs.writeFileSync(path.join(root,'workers/chabaquito/worker-preview.js'),output);
console.log('Worker de archivo único generado.');
