package com.visitaloja.app

import android.Manifest
import android.content.Intent
import android.net.Uri
import android.os.SystemClock
import androidx.activity.compose.BackHandler
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.itemsIndexed
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.runtime.saveable.rememberSaveable
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.lifecycle.Lifecycle
import androidx.lifecycle.LifecycleEventObserver
import androidx.lifecycle.compose.LocalLifecycleOwner
import androidx.lifecycle.repeatOnLifecycle
import kotlinx.coroutines.delay
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

@OptIn(ExperimentalLayoutApi::class)
@Composable
internal fun RoutePlannerScreen(state: PlacesState, refresh: () -> Unit, close: () -> Unit, open: (Place) -> Unit, use: (List<String>, String) -> Unit) {
    val context=LocalContext.current;val lifecycle=LocalLifecycleOwner.current.lifecycle
    var minutes by rememberSaveable{mutableIntStateOf(60)};var category by rememberSaveable{mutableStateOf("all")}
    var transport by rememberSaveable{mutableStateOf("walk")};var intensity by rememberSaveable{mutableStateOf("balanced")};var openOnly by rememberSaveable{mutableStateOf(false)}
    var gps by remember{mutableStateOf(false)};var fix by remember{mutableStateOf<MapFix?>(null)};var locating by remember{mutableStateOf(false)}
    var locationMessage by remember{mutableStateOf<String?>(null)};var message by remember{mutableStateOf<String?>(null)}
    var generated by remember{mutableStateOf<SuggestedRoute?>(null)};var now by remember{mutableLongStateOf(System.currentTimeMillis())}
    val tracker=remember(context){MapLocation(context)}
    val preferences=RoutePreferences(minutes,category,transport,intensity,openOnly)
    val origin=if(gps)fix?.let{RouteOrigin(it.latitude,it.longitude,"Tu ubicación al preparar")} else RoutePlannerPolicy.centre
    val fixReady=!gps||fix?.let{MapLocationPolicy.valid(it,SystemClock.elapsedRealtime())&&it.accuracy<=1000}==true
    val fresh=RoutePlannerPolicy.fresh(state,now)
    val plan=generated?.takeIf{it.preferences==preferences&&it.origin==origin&&RoutePlannerPolicy.usable(it,state,now)}
    BackHandler(onBack=close)
    LaunchedEffect(Unit){refresh()}
    LaunchedEffect(lifecycle){lifecycle.repeatOnLifecycle(Lifecycle.State.STARTED){while(true){now=System.currentTimeMillis();delay(1000)}}}
    LaunchedEffect(locating){if(!locating)tracker.cancel() else {delay(30_000);if(locating){tracker.cancel();locating=false;locationMessage="No encontramos una ubicación suficientemente precisa. Reintenta o usa el centro de Loja."}}}
    DisposableEffect(tracker,lifecycle){
        val observer=LifecycleEventObserver{_,event->if(event==Lifecycle.Event.ON_STOP){tracker.cancel();locating=false;fix=null;generated=null}}
        lifecycle.addObserver(observer)
        onDispose{lifecycle.removeObserver(observer);tracker.cancel()}
    }
    fun locate(){
        if(!lifecycle.currentState.isAtLeast(Lifecycle.State.STARTED))return
        gps=true;fix=null;generated=null;locating=true;locationMessage="Buscando tu ubicación…"
        tracker.start{value->
            val point=value.fix
            if(point!=null&&MapLocationPolicy.valid(point,SystemClock.elapsedRealtime())&&point.accuracy<=1000){
                fix=point;locating=false;locationMessage=if(point.accuracy>100)"Ubicación aproximada · ±${point.accuracy.toInt()} m" else "Ubicación recibida · ±${point.accuracy.toInt()} m"
            } else if(value.problem!=MapLocationProblem.NONE){
                locating=false;locationMessage=when(value.problem){MapLocationProblem.DISABLED->"Activa la ubicación del móvil y vuelve a intentar.";MapLocationProblem.PERMISSION->"Permite la ubicación o usa el centro de Loja.";else->"No encontramos una ubicación suficientemente precisa. Reintenta o usa el centro de Loja."}
            } else if(point!=null)locationMessage="Afinando la ubicación; la precisión actual es ±${point.accuracy.toInt()} m."
        }
    }
    val permission=rememberLauncherForActivityResult(ActivityResultContracts.RequestMultiplePermissions()){if(tracker.hasPermission())locate() else {gps=false;locating=false;locationMessage="Puedes preparar tu recorrido desde el centro de Loja sin dar permiso."}}
    fun external(intent:Intent){runCatching{context.startActivity(intent)}.onFailure{message="No hay una aplicación disponible para abrir esta opción."}}
    LazyColumn(Modifier.fillMaxSize().testTag("route-planner-screen"),contentPadding=PaddingValues(start=20.dp,end=20.dp,top=12.dp,bottom=88.dp),verticalArrangement=Arrangement.spacedBy(12.dp)) {
        item {
            TextButton(onClick=close,modifier=Modifier.testTag("planner-close")){Text("← Volver a Mi recorrido")}
            Text("Un plan para descubrir Loja",style=MaterialTheme.typography.headlineSmall,fontWeight=FontWeight.Bold)
            Text("Elige tu tiempo y tus intereses. Usamos únicamente paradas publicadas.",style=MaterialTheme.typography.bodyMedium)
        }
        item {
            Text("Tiempo disponible",fontWeight=FontWeight.Bold)
            FlowRow(horizontalArrangement=Arrangement.spacedBy(8.dp)){listOf(60 to "1 hora",240 to "Medio día",480 to "Día completo").forEach{(id,label)->FilterChip(minutes==id,{minutes=id;generated=null},label={Text(label)},modifier=Modifier.testTag("planner-time-$id"))}}
        }
        item {
            Text("¿Qué te interesa?",fontWeight=FontWeight.Bold)
            FlowRow(horizontalArrangement=Arrangement.spacedBy(8.dp)){RoutePlannerPolicy.categories.forEach{(id,label)->FilterChip(category==id,{category=id;generated=null},label={Text(label)},modifier=Modifier.testTag("planner-category-$id"))}}
        }
        item {
            Text("¿Cómo te movilizas?",fontWeight=FontWeight.Bold)
            FlowRow(horizontalArrangement=Arrangement.spacedBy(8.dp)){listOf("walk" to "Caminando","drive" to "En vehículo").forEach{(id,label)->FilterChip(transport==id,{transport=id;generated=null},label={Text(label)},modifier=Modifier.testTag("planner-transport-$id"))}}
            Text("Tipo de recorrido",fontWeight=FontWeight.Bold)
            FlowRow(horizontalArrangement=Arrangement.spacedBy(8.dp)){listOf("short" to "Esencial","balanced" to "Equilibrado","complete" to "Completo").forEach{(id,label)->FilterChip(intensity==id,{intensity=id;generated=null},label={Text(label)})}}
        }
        item {
            Text("Punto de partida",fontWeight=FontWeight.Bold)
            Text(if(gps)locationMessage.orEmpty() else "Centro de Loja · referencia de la web")
            OutlinedButton(onClick={if(tracker.hasPermission())locate() else permission.launch(arrayOf(Manifest.permission.ACCESS_COARSE_LOCATION,Manifest.permission.ACCESS_FINE_LOCATION))},enabled=!locating,modifier=Modifier.testTag("planner-location")){Text(if(locating)"Buscando ubicación…" else "Usar mi ubicación actual")}
            if(gps)TextButton(onClick={tracker.cancel();gps=false;fix=null;locating=false;generated=null}){Text("Usar el centro de Loja")}
            if(gps&&!locating&&!fixReady)Text("Actualiza la ubicación antes de preparar otro plan.",style=MaterialTheme.typography.bodySmall)
            Text("La ubicación se usa en este momento y no se guarda con tu recorrido.",style=MaterialTheme.typography.bodySmall)
            Row { Checkbox(openOnly,{openOnly=it;generated=null});Column(Modifier.weight(1f)){Text("Solo con horario verificable al llegar",fontWeight=FontWeight.Medium);Text("Los horarios escritos que no podemos comprobar quedan fuera de esta selección.",style=MaterialTheme.typography.bodySmall)} }
        }
        item {
            if(!fresh){Text(if(state.loading)"Consultando paradas publicadas…" else "Conéctate y actualiza las paradas para preparar o guardar el recorrido.");OutlinedButton(onClick=refresh,enabled=!state.loading,modifier=Modifier.testTag("planner-refresh")){Text("Actualizar paradas")}}
            Button(onClick={origin?.let{generated=RoutePlannerPolicy.build(state,preferences,it,System.currentTimeMillis());message=null}},enabled=fresh&&fixReady&&!locating,modifier=Modifier.fillMaxWidth().testTag("planner-generate")){Text("Preparar mi recorrido")}
        }
        message?.let{text->item{Text(text,color=MaterialTheme.colorScheme.error)}}
        if(generated!=null&&plan==null&&generated?.stops?.isNotEmpty()==true)item{Text("La propuesta necesita actualizarse. Vuelve a prepararla antes de usarla.")}
        if(generated?.stops?.isEmpty()==true)item{Text("No encontramos paradas que encajen en ese tiempo y selección. Prueba con medio día, vehículo o sin el filtro de horarios.",modifier=Modifier.testTag("planner-empty"))}
        if(plan!=null) {
            item {
                Card(Modifier.fillMaxWidth().testTag("planner-results")){Column(Modifier.padding(16.dp),verticalArrangement=Arrangement.spacedBy(7.dp)){
                    Text("${plan.stops.size} paradas · ${plan.minutes} min orientativos",style=MaterialTheme.typography.titleMedium,fontWeight=FontWeight.Bold)
                    Text("${RoutePlannerPolicy.km(plan.distanceKm)} en línea recta · desde ${plan.origin.label}")
                    Text("Traslados y visitas son estimados. Revisa el trayecto y los horarios antes de salir.",style=MaterialTheme.typography.bodySmall)
                }}
            }
            itemsIndexed(plan.stops,key={_,stop->stop.id}){index,stop->
                val place=state.places.first{it.id==stop.id}
                val arrival=Instant.ofEpochMilli(plan.generatedAt+stop.arrivalMinutes*60_000L).atZone(ZoneId.of("America/Guayaquil")).format(DateTimeFormatter.ofPattern("HH:mm"))
                OutlinedCard(Modifier.fillMaxWidth().testTag("planner-stop-${stop.id}")){Column(Modifier.padding(16.dp),verticalArrangement=Arrangement.spacedBy(6.dp)){
                    Text("${index+1}. ${place.title}",fontWeight=FontWeight.Bold)
                    Text(place.address.ifBlank{"Loja, Ecuador"},style=MaterialTheme.typography.bodySmall)
                    Text("Llegada orientativa $arrival · ${stop.travelMinutes} min de traslado · ${stop.visitMinutes} min de visita",style=MaterialTheme.typography.bodySmall)
                    FlowRow(horizontalArrangement=Arrangement.spacedBy(8.dp)) {
                        TextButton(onClick={open(place)}){Text("Ver parada")}
                        TextButton(onClick={external(Intent(Intent.ACTION_VIEW,Uri.parse("https://www.google.com/maps/dir/?api=1&destination=${place.latitude},${place.longitude}&travelmode=${if(transport=="drive")"driving" else "walking"}")))}){Text("Cómo llegar")}
                    }
                }}
            }
            item {
                Button(onClick={if(RoutePlannerPolicy.usable(plan,state,System.currentTimeMillis()))use(plan.stops.map{it.id},plan.preferences.transport) else message="Actualiza la propuesta antes de guardarla."},modifier=Modifier.fillMaxWidth().testTag("planner-use")){Text("Guardar este plan en Mi recorrido")}
                Text("Se guardan las paradas en este móvil para esta cuenta. Tus favoritos se conservan.",style=MaterialTheme.typography.bodySmall)
                OutlinedButton(onClick={if(RoutePlannerPolicy.usable(plan,state,System.currentTimeMillis())){
                    val text="Mi recorrido de VisitaLoja · ${plan.minutes} min orientativos\n\n"+plan.stops.mapIndexed{index,stop->state.places.first{it.id==stop.id}.let{"${index+1}. ${it.title}\n${PlacePolicy.publicUrl(it)}"}}.joinToString("\n\n")
                    external(Intent.createChooser(Intent(Intent.ACTION_SEND).setType("text/plain").putExtra(Intent.EXTRA_TEXT,text),"Compartir mi recorrido"))
                }else message="Actualiza la propuesta antes de compartirla."},modifier=Modifier.fillMaxWidth().testTag("planner-share")){Text("Compartir propuesta")}
            }
        }
    }
}
